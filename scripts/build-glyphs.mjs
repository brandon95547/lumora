// Writes the few music glyphs the staff draws (clefs, accidentals, brace) as path data,
// taken from the Bravura font (SIL Open Font License). The app then draws them with
// Path2D, so no font file is loaded and every machine renders the same shapes.
//
// Units: one staff space = 1. The glyph origin sits on the baseline, y grows downward.
import { readFileSync, writeFileSync } from 'node:fs';
import { createRequire } from 'node:module';
import opentype from 'opentype.js';

const require = createRequire(import.meta.url);
const fontPath = require.resolve('@vexflow-fonts/bravura/bravura.otf');
const font = opentype.parse(readFileSync(fontPath).buffer);
const SPACE = font.unitsPerEm / 4; // SMuFL: the em is four staff spaces.

const GLYPHS = {
  gClef: 0xe050,
  fClef: 0xe062,
  brace: 0xe000,
  sharp: 0xe262,
  flat: 0xe260,
  natural: 0xe261,
};

const round = (n) => Math.round(n * 1000) / 1000;
const out = {};
for (const [name, code] of Object.entries(GLYPHS)) {
  const glyph = font.charToGlyph(String.fromCodePoint(code));
  const path = glyph.getPath(0, 0, 4); // the em is four spaces, so 1 space = 1
  const box = path.getBoundingBox();
  out[name] = {
    d: path.toPathData(3),
    advance: round(glyph.advanceWidth / SPACE),
    box: [round(box.x1), round(box.y1), round(box.x2), round(box.y2)],
  };
}

const file = new URL('../src/shared/scene/glyphs.js', import.meta.url);
writeFileSync(
  file,
  `// Generated by scripts/build-glyphs.mjs from Bravura (SIL OFL 1.1). Do not edit.\n` +
    `// Units: one staff space = 1; origin on the baseline; y grows downward.\n` +
    `export const GLYPHS = ${JSON.stringify(out, null, 2)};\n`,
);
console.log(`wrote ${Object.keys(out).length} glyphs to src/shared/scene/glyphs.js`);
